"""
Outcome eval runner — Phase 0 skeleton.

What this skeleton does:
- Loads chio-pack/eval/outcomes.yml.
- Discovers fixtures per eval (skipping files marked `_example: true`).
- Reports each eval's status: blocked-fixtures (need more) or blocked-runner (Phase 1).
- Refuses to claim a baseline. Real runners land in Phase 1.
- Writes a markdown status report to the path given by --report.

What this skeleton does NOT do:
- Run any of the four outcome evals (time-to-fix, repeated-mistake,
  conformance-recall, capability-error-explanation). Those land in Phase 1.

Exit codes:
    0 — every eval is "ok" (impossible in Phase 0, since runners aren't built)
    1 — at least one eval is blocked
    2 — config / IO error

See chio-pack/eval/PHASE-0.md for the canonical eval definitions.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import glob as _glob
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:  # pragma: no cover
    print("error: PyYAML required (run `uv sync` in chio-pack/)", file=sys.stderr)
    sys.exit(2)


# === data ===

@dataclass
class EvalSpec:
    id: str
    type: str
    fixtures_glob: str | None
    fixture_count_min: int | None
    baseline_required: bool
    target: dict[str, Any]
    regression_threshold: float | None
    extra: dict[str, Any] = field(default_factory=dict)


@dataclass
class EvalResult:
    spec: EvalSpec
    fixture_count: int
    status: str       # "ok" | "blocked-fixtures" | "blocked-runner" | "skipped"
    message: str


# === config loading ===

def load_config(path: Path) -> tuple[list[EvalSpec], dict[str, Any], list[dict[str, Any]]]:
    with path.open() as f:
        cfg = yaml.safe_load(f) or {}
    evals: list[EvalSpec] = []
    for entry in cfg.get("evals", []):
        evals.append(
            EvalSpec(
                id                  = entry["id"],
                type                = entry.get("type", "unknown"),
                fixtures_glob       = entry.get("fixtures"),
                fixture_count_min   = entry.get("fixture_count_min"),
                baseline_required   = bool(entry.get("baseline_required", False)),
                target              = entry.get("target", {}),
                regression_threshold = entry.get("regression_threshold"),
                extra               = entry,
            )
        )
    reporting = cfg.get("reporting", {}) or {}
    deferred  = cfg.get("deferred", []) or []
    return evals, reporting, deferred


# === fixture discovery ===

def discover_fixtures(spec: EvalSpec, base: Path) -> list[Path]:
    """Glob for fixture files; skip those with `_example: true`."""
    if not spec.fixtures_glob:
        return []
    pattern = str(base / spec.fixtures_glob)
    paths = [Path(p) for p in _glob.glob(pattern)]
    real: list[Path] = []
    for p in paths:
        try:
            with p.open() as f:
                payload = yaml.safe_load(f) or {}
        except Exception:
            continue
        if isinstance(payload, dict) and payload.get("_example") is True:
            continue
        real.append(p)
    return sorted(real)


# === Phase 0 evaluation logic ===

def evaluate_one(spec: EvalSpec, base: Path) -> EvalResult:
    if not spec.fixtures_glob:
        # Some evals (e.g., repeated-mistake-rate) consume session logs, not fixtures.
        return EvalResult(
            spec          = spec,
            fixture_count = 0,
            status        = "blocked-runner",
            message       = "no fixtures glob; runner is Phase 1 deliverable",
        )

    fixtures = discover_fixtures(spec, base)
    fixture_count = len(fixtures)
    fixture_min   = spec.fixture_count_min or 0

    if fixture_count < fixture_min:
        return EvalResult(
            spec          = spec,
            fixture_count = fixture_count,
            status        = "blocked-fixtures",
            message       = f"have {fixture_count}, need ≥ {fixture_min} (PHASE-0.md)",
        )

    return EvalResult(
        spec          = spec,
        fixture_count = fixture_count,
        status        = "blocked-runner",
        message       = "fixtures present; runner is Phase 1 deliverable",
    )


# === report rendering ===

_STATUS_MARKER = {
    "ok":               "ok",
    "blocked-fixtures": "BLOCKED — fixtures",
    "blocked-runner":   "BLOCKED — runner",
    "skipped":          "skipped",
}


def render_report(results: list[EvalResult], deferred: list[dict[str, Any]]) -> str:
    when = _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        f"# Outcome evals — {when}",
        "",
        "> Generated by `chio-pack-eval` Phase 0 skeleton. No real runners yet — see PHASE-0.md.",
        "",
        "| Eval | Fixtures | Status | Notes |",
        "| ---- | -------- | ------ | ----- |",
    ]
    for r in results:
        marker = _STATUS_MARKER.get(r.status, r.status)
        lines.append(f"| `{r.spec.id}` | {r.fixture_count} | {marker} | {r.message} |")

    if deferred:
        lines.append("")
        lines.append("## Deferred (block on Phase 2)")
        lines.append("")
        for d in deferred:
            note = d.get("note", "")
            lines.append(f"- `{d['id']}` — blocked until **{d.get('blocked_until', '?')}**: {note}")

    lines.append("")
    return "\n".join(lines)


def write_report(report: str, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report)


# === main ===

def main() -> int:
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("--suite", default="outcomes", choices=["outcomes", "retrieval", "all"])
    p.add_argument("--config", default="eval/outcomes.yml", help="path to outcomes.yml")
    p.add_argument("--report", default=None, help="path to write markdown report (optional)")
    p.add_argument("--format", default="markdown", choices=["markdown", "json"])
    args = p.parse_args()

    if args.suite == "retrieval":
        print("blocked: retrieval suite runs inside the Phase 1 docker stack")
        print("         use `make kb-eval-retrieval` once the stack is up")
        return 2

    config_path = Path(args.config)
    if not config_path.exists():
        print(f"error: config {config_path} not found", file=sys.stderr)
        return 2

    base = config_path.parent
    evals, _reporting, deferred = load_config(config_path)
    if not evals:
        print(f"error: no evals declared in {config_path}", file=sys.stderr)
        return 2

    results = [evaluate_one(spec, base) for spec in evals]

    if args.format == "json":
        out = {
            "run_at": _dt.datetime.now(_dt.timezone.utc).isoformat(),
            "evals": [
                {
                    "id":            r.spec.id,
                    "fixture_count": r.fixture_count,
                    "status":        r.status,
                    "message":       r.message,
                }
                for r in results
            ],
            "deferred": deferred,
        }
        print(json.dumps(out, indent=2))
    else:
        report = render_report(results, deferred)
        if args.report:
            write_report(report, Path(args.report))
            print(f"wrote {args.report}")
        else:
            print(report)

    blocked = [r for r in results if r.status.startswith("blocked")]
    if blocked:
        print(
            f"\n{len(blocked)} eval(s) blocked. Phase 0 incomplete — see PHASE-0.md.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
